<script>
document.addEventListener("DOMContentLoaded", function () {

    const ageModal = document.getElementById("age-verification-modal");
    const ruoModal = document.getElementById("ruo-modal");

    const yesBtn = document.getElementById("age-verify-yes");
    const noBtn = document.getElementById("age-verify-no");
    const ruoBtn = document.getElementById("ruo-policy-btn");
    const ruoClose = document.getElementById("ruo-close-btn");
    const closeIcon = document.querySelector(".close-ruo-modal");

    // Show age modal
    if (sessionStorage.getItem("ageVerified") !== "true") {
        ageModal.classList.remove("age-modal-hidden");
        document.body.style.overflow = "hidden";
    }

    // YES
    yesBtn.addEventListener("click", function () {
        sessionStorage.setItem("ageVerified", "true");
        ageModal.classList.add("age-modal-hidden");
        document.body.style.overflow = "auto";
    });

    // NO
    noBtn.addEventListener("click", function () {
        ageModal.querySelector(".age-verification-content").innerHTML =
            "<h2>Access Denied</h2><p>You must be 21 years or older to view this website.</p>";
    });

    // Open RUO popup
    ruoBtn.addEventListener("click", function () {
        ruoModal.classList.remove("age-modal-hidden");
    });

    // Close RUO popup
    function closeRUO() {
        ruoModal.classList.add("age-modal-hidden");
    }

    ruoClose.addEventListener("click", closeRUO);
    closeIcon.addEventListener("click", closeRUO);

});
</script>

